// Generates packages/sdk/src/abis.ts from forge artifacts (run `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["WarrantVault", "WarrantFactory", "AgentRegistry"];
let out = "// AUTO-GENERATED by scripts/gen-abis.mjs from forge artifacts. Do not edit.\n\n";
for (const name of contracts) {
  const art = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const abi = art.abi.filter((e) => e.type !== "constructor" || true);
  const key = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${key} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages/sdk/src/abis.ts"), out);
console.log("wrote packages/sdk/src/abis.ts");

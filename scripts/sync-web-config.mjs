#!/usr/bin/env node
// Writes web/lib/deployment.ts from deployments/<name>.json so the dashboard's defaults match the deployment.
// usage: node scripts/sync-web-config.mjs [name=aevum]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const name = process.argv[2] ?? "aevum";
const d = JSON.parse(readFileSync(resolve(root, `deployments/${name}.json`), "utf8"));
const out = `// Generated by scripts/sync-web-config.mjs from deployments/${name}.json. Do not edit by hand.
export const DEPLOYMENT = {
  chainId: ${d.chainId},
  factory: "${d.WarrantFactory.address}",
  registry: "${d.AgentRegistry.address}",
  token: "${d.tUSD8}",
  deployBlock: ${d.deployBlock},
} as const;
`;
writeFileSync(resolve(root, "web/lib/deployment.ts"), out);
console.log("wrote web/lib/deployment.ts");

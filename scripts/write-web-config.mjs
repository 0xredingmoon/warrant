// Writes web/public/config.js from environment variables, for hosts that build the static dashboard themselves
// (GitHub Pages, Render static site, Netlify, Cloudflare Pages, ...). Unset or placeholder values keep the committed defaults.
//   RELAYER_URL=https://relayer.example.com node scripts/write-web-config.mjs
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const keys = { RELAYER_URL: "relayerUrl", RPC_URL: "rpcUrl", EXPLORER_URL: "explorer", INDEXER_URL: "indexerUrl", FACTORY_ADDRESS: "factory", REGISTRY_ADDRESS: "registry" };

function usable(raw) {
  const v = (raw ?? "").trim();
  if (!v) return false;
  const lower = v.toLowerCase();
  if (lower === "pending" || lower === "placeholder" || lower === "unset" || lower === "none") return false;
  try {
    const u = new URL(v);
    if (u.hostname === "localhost" || u.hostname === "127.0.0.1" || u.hostname === "::1") return false;
  } catch {
    // non-URL values (addresses) are fine
  }
  return true;
}

const cfg = Object.fromEntries(Object.entries(keys).filter(([k]) => usable(process.env[k])).map(([k, v]) => [v, process.env[k].trim().replace(/\/$/, "")]));
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../web/public/config.js");
writeFileSync(out, `// generated by scripts/write-web-config.mjs\nwindow.__WARRANT__ = ${JSON.stringify(cfg, null, 2)};\n`);
console.log(`wrote web/public/config.js: ${Object.keys(cfg).join(", ") || "(defaults)"}`);
